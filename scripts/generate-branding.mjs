import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
const root = new URL('../', import.meta.url);
const data = JSON.parse(readFileSync(new URL('assets/branding/coffee-mark.json', root), 'utf8'));
const light = { ink:'#0f172a', accent:'#126449', paper:'#ffffff', muted:'#475569', warm:'#854d0e' };
const dark = { ink:'#f1f5f9', accent:'#94e8c3', paper:'#0b1014', muted:'#94a3b8', warm:'#fcd34d' };
function svg(colors, responsive = false, mono = false) {
  const vars = palette => Object.entries(palette).map(([key,value]) => `--brand-${key}:${value}`).join(';');
  const style = mono ? '' : `<style>:root{${vars(colors)}}${responsive ? `@media(prefers-color-scheme:dark){:root{${vars(dark)}}}` : ''}</style>`;
  const rects = data.rects.map(([x,y,width,height,role]) => `<rect x="${x}" y="${y}" width="${width}" height="${height}" fill="${mono ? 'currentColor' : `var(--brand-${role})`}"/>`).join('');
  // Mono keeps the mug recognizable without relying on overlapping fill colors.
  const monoRects = mono ? data.rects.filter(([, , , ,role]) => role==='ink'||role==='muted').map(([x,y,width,height])=>`<rect x="${x}" y="${y}" width="${width}" height="${height}"/>`).join('') : rects;
  return `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 32 32" width="96" height="96" shape-rendering="crispEdges" fill="currentColor" role="img" aria-label="StudyStreak coffee mark"><title>StudyStreak</title>${style}${monoRects}</svg>\n`;
}
const outputs = new Map([
  ['frontend-web/src/components/branding/mark.ts', '// Generated by scripts/generate-branding.mjs; edit assets/branding/coffee-mark.json.\nexport default '+JSON.stringify(data,null,2)+' as const;\n'],
  ['frontend-mobile/src/components/branding/mark.ts', '// Generated by scripts/generate-branding.mjs; edit assets/branding/coffee-mark.json.\nexport default '+JSON.stringify(data,null,2)+' as const;\n'],
  ['assets/branding/studystreak-mark-light.svg', svg(light)],
  ['assets/branding/studystreak-mark-dark.svg', svg(dark)],
  ['assets/branding/studystreak-mark-mono.svg', svg(light,false,true)],
  ['frontend-web/public/favicon.svg', svg(light,true)],
]);
for(const [path,content] of outputs) {
  const target=new URL(path,root);
  if(process.argv.includes('--check')) {
    if(readFileSync(target,'utf8')!==content)throw new Error(`Brand asset out of sync: ${path}`);
  } else writeFileSync(target,content);
}
process.stdout.write(`Brand assets ${process.argv.includes('--check')?'verified':'generated'} from ${fileURLToPath(new URL('assets/branding/coffee-mark.json',root))}.\n`);
