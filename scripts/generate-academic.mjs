import {readFileSync,writeFileSync} from 'node:fs';
const root=new URL('../',import.meta.url),data=JSON.parse(readFileSync(new URL('assets/academic/glyphs.json',root),'utf8'));
for(const [name,rects]of Object.entries(data))if(name!=='grid')for(const [x,y,w,h,role]of rects)if(x<0||y<0||w<=0||h<=0||x+w>data.grid||y+h>data.grid||!['ink','accent','paper','muted'].includes(role))throw Error('Invalid academic glyph');
const output='// Generated by scripts/generate-academic.mjs; edit assets/academic/glyphs.json.\nexport default '+JSON.stringify(data,null,2)+' as const;\n';
for(const target of ['frontend-web','frontend-mobile']){
 const file=new URL(`${target}/src/components/academic/glyphs.ts`,root);
 if(process.argv.includes('--check')){if(readFileSync(file,'utf8')!==output)throw Error('Academic glyphs out of sync');}else writeFileSync(file,output);
}
console.log('Academic glyphs verified.');
